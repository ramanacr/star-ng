// Generated themes of the package. Each theme comes from the theme factory
// (`projects/star-ng/theme-factory`, `starCreateTheme` and `starThemeCss`) and is written to
// `projects/star-ng/styles/themes/_<name>.scss`, so consumers can `@use` it. `build-styles.mjs`
// also compiles each one to `dist/star-ng/styles/themes/<name>.css`.
//
//   node tools/gen-themes.mjs           writes the theme files
//   node tools/gen-themes.mjs --check   fails when a written file is out of date (`lint` runs it)
//
// The factory is TypeScript without Angular imports. The tool transpiles its files with the
// TypeScript compiler into a temporary folder and imports them, so the tool and the library run
// the same code.
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';
import ts from 'typescript';

export const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const factoryDir = join(root, 'projects/star-ng/theme-factory');
export const themesDir = join(root, 'projects/star-ng/styles/themes');

/** The themes of the package: factory inputs. */
export const THEMES = [
  // Glass: translucent floating layers. A neutral name: no product or vendor name.
  { name: 'glass', hue: 265, opacity: 0.55, blur: 20, tint: 0.3, radius: 1.25, angle: 135 },
];

/** Imports the theme factory from its TypeScript source. */
export async function loadFactory() {
  const out = mkdtempSync(join(tmpdir(), 'star-theme-factory-'));
  try {
    for (const file of readdirSync(factoryDir)) {
      if (!file.endsWith('.ts') || file.endsWith('.spec.ts')) continue;
      const { outputText } = ts.transpileModule(readFileSync(join(factoryDir, file), 'utf8'), {
        compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
      });
      const js = outputText.replace(/from '\.\/([\w-]+)'/g, "from './$1.mjs'");
      writeFileSync(join(out, file.replace(/\.ts$/, '.mjs')), js);
    }
    return await import(pathToFileURL(join(out, 'index.mjs')).href);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

/** The content of each theme file, formatted like the rest of the repository. */
export async function renderThemes() {
  const factory = await loadFactory();
  const config = (await prettier.resolveConfig(join(themesDir, '_x.scss'))) ?? {};
  const files = new Map();
  for (const options of THEMES) {
    const theme = factory.starCreateTheme(options);
    const failed = theme.contrast.filter((check) => !check.pass);
    if (failed.length) {
      throw new Error(
        `Theme "${options.name}" fails ${failed.length} contrast checks, for example ` +
          JSON.stringify(failed[0]),
      );
    }
    const header = [
      `// Theme "${options.name}". Generated by tools/gen-themes.mjs from the theme factory`,
      '// (@star-ng/ui/theme-factory): do not edit; change the inputs in the tool and run',
      '// `corepack pnpm themes:gen`.',
      '//',
      `//   @use '@star-ng/ui/styles/star-ng';`,
      `//   @use '@star-ng/ui/styles/themes/${options.name}';`,
      '//',
      `//   <html data-star-theme="${options.name}" data-star-theme-variant="tinted">`,
      '//',
      `// Inputs: ${JSON.stringify(theme.options)}`,
      `// Surface opacity after the contrast check: ${JSON.stringify(theme.alpha)}`,
      '',
    ].join('\n');
    const css = factory.starThemeCss(theme);
    const formatted = await prettier.format(`${header}${css}`, {
      ...config,
      plugins: [],
      parser: 'scss',
    });
    files.set(join(themesDir, `_${options.name}.scss`), formatted);
  }
  return files;
}

async function main() {
  const check = process.argv.includes('--check');
  const files = await renderThemes();
  let stale = 0;
  mkdirSync(themesDir, { recursive: true });
  for (const [file, content] of files) {
    let current = null;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // A new theme: no file yet.
    }
    if (current === content) continue;
    if (check) {
      console.error(`${file} is out of date. Run \`corepack pnpm themes:gen\`.`);
      stale++;
    } else {
      writeFileSync(file, content);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
